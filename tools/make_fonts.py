#!/usr/bin/env python3
"""
Rasterize TrueType fonts into Adafruit-GFX 'GFXfont' headers for Arduino_GFX.
Default face is DejaVu Sans Bold (free license). Needs Pillow.

  python3 tools/make_fonts.py [--ttf /path/to/font.ttf]
"""
import argparse, os
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUTDIR = os.path.join(HERE, "..", "TacoCompass")

# name, pixel size, first char, last char
FONTS = [
    ("FontBig", 84, ".", "9"),     # distance digits: . / 0-9
    ("FontMed", 34, " ", "~"),
    ("FontSmall", 24, " ", "~"),
]


def render(ttf, name, size, first, last):
    font = ImageFont.truetype(ttf, size)
    ascent, descent = font.getmetrics()
    pad = size
    bitmap = bytearray()
    glyphs = []
    for code in range(ord(first), ord(last) + 1):
        ch = chr(code)
        W, H = size * 3, size * 3
        img = Image.new("L", (W, H), 0)
        ImageDraw.Draw(img).text((pad, pad + ascent), ch, font=font, fill=255, anchor="ls")
        mono = img.point(lambda v: 255 if v >= 128 else 0)
        bbox = mono.getbbox()
        adv = int(round(font.getlength(ch)))
        if bbox is None:  # space etc.
            glyphs.append((len(bitmap), 0, 0, adv, 0, 0))
            continue
        x0, y0, x1, y1 = bbox
        w, h = x1 - x0, y1 - y0
        bits, nbits, acc = bytearray(), 0, 0
        px = mono.load()
        for yy in range(y0, y1):
            for xx in range(x0, x1):
                acc = (acc << 1) | (1 if px[xx, yy] else 0)
                nbits += 1
                if nbits == 8:
                    bits.append(acc); acc = 0; nbits = 0
        if nbits:
            bits.append(acc << (8 - nbits))
        glyphs.append((len(bitmap), w, h, adv, x0 - pad, y0 - (pad + ascent)))
        bitmap += bits
    assert len(bitmap) < 65536, f"{name} too big for GFXfont ({len(bitmap)} bytes)"
    y_adv = ascent + descent
    path = os.path.join(OUTDIR, f"{name.lower()}.h")
    with open(path, "w", newline="\n") as f:
        f.write(f"// GENERATED by tools/make_fonts.py from {os.path.basename(ttf)} @ {size}px\n")
        f.write("#pragma once\n#include <stdint.h>\n#include <gfxfont.h>\n\n")
        f.write(f"static const uint8_t {name}Bitmaps[] = {{\n")
        for i in range(0, len(bitmap), 24):
            f.write("  " + ",".join(f"0x{b:02X}" for b in bitmap[i:i + 24]) + ",\n")
        f.write("};\n\n")
        f.write(f"static const GFXglyph {name}Glyphs[] = {{\n")
        for code, g in zip(range(ord(first), ord(last) + 1), glyphs):
            c = chr(code)
            cmt = c if c not in "\\" else "backslash"
            f.write(f"  {{{g[0]},{g[1]},{g[2]},{g[3]},{g[4]},{g[5]}}},  // '{cmt}'\n")
        f.write("};\n\n")
        f.write(f"static const GFXfont {name} = {{(uint8_t*){name}Bitmaps, (GFXglyph*){name}Glyphs, "
                f"0x{ord(first):02X}, 0x{ord(last):02X}, {y_adv}}};\n")
    print(f"{path}: {len(glyphs)} glyphs, {len(bitmap)} bytes")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ttf", default="/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf")
    a = ap.parse_args()
    for spec in FONTS:
        render(a.ttf, *spec)


if __name__ == "__main__":
    main()
