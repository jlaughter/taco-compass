#!/usr/bin/env python3
"""
Build TacoCompass/decl_grid.h — a global 2-degree grid of magnetic declination
from the World Magnetic Model 2025 (valid 2025-2030), so the compass can turn a
magnetic heading into a true one without any network access.

  pip install pygeomag
  python3 tools/build_decl.py            # epoch = today
  python3 tools/build_decl.py --year 2027.5
"""
import argparse, datetime, os

from pygeomag import GeoMag

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "TacoCompass", "decl_grid.h")
LAT0, LAT1, LON0, LON1, STEP = -80, 84, -180, 180, 2


def main():
    t = datetime.date.today()
    ap = argparse.ArgumentParser()
    ap.add_argument("--year", type=float, default=t.year + (t.timetuple().tm_yday - 1) / 365.25)
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args()
    gm = GeoMag(coefficients_file="wmm/WMM_2025.COF")
    rows = (LAT1 - LAT0) // STEP + 1
    cols = (LON1 - LON0) // STEP + 1
    vals = []
    for i in range(rows):
        lat = LAT0 + i * STEP
        for j in range(cols):
            lon = LON0 + j * STEP
            d = gm.calculate(glat=lat, glon=lon, alt=0, time=a.year).d
            vals.append(int(round(d * 10)))
    with open(a.out, "w", newline="\n") as f:
        f.write("// GENERATED by tools/build_decl.py from WMM2025 — do not edit.\n")
        f.write(f"// Epoch {a.year:.2f}. Declination in tenths of a degree, east positive.\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define DECL_LAT0 {LAT0}\n#define DECL_LON0 {LON0}\n#define DECL_STEP {STEP}\n")
        f.write(f"#define DECL_ROWS {rows}\n#define DECL_COLS {cols}\n\n")
        f.write("static const int16_t DECL_GRID[DECL_ROWS * DECL_COLS] = {\n")
        for i in range(rows):
            line = ",".join(str(v) for v in vals[i * cols:(i + 1) * cols])
            f.write(f"  {line},  // lat {LAT0 + i * STEP}\n")
        f.write("};\n")
    print(f"Wrote {a.out}: {rows}x{cols}, epoch {a.year:.2f}")


if __name__ == "__main__":
    main()
